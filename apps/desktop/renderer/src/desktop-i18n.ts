export type DesktopLocale = 'zh-CN' | 'en-US';

export function normalizeDesktopLocale(value?: string | null): DesktopLocale {
  const normalized = String(value || '').trim().toLowerCase();
  if (normalized.startsWith('en')) return 'en-US';
  return 'zh-CN';
}

export function detectDesktopLocale(): DesktopLocale {
  const navigatorLocale = typeof navigator === 'undefined'
    ? ''
    : (navigator.languages?.find(Boolean) || navigator.language || '');
  const intlLocale = Intl.DateTimeFormat().resolvedOptions().locale;
  return normalizeDesktopLocale(navigatorLocale || intlLocale);
}

